"""Generate supabase/migrations/*_seed_data.sql from the project's data.

Goals, prizes and rates mirror src/data/sample.ts and the "Cum adaugi timp"
section; challenges come from data/challenges.json.
Run: python3 scripts/gen-seed.py
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
out = root / "supabase/migrations/20261119193600_seed_data.sql"


def q(s):
    return "null" if s is None else "'" + str(s).replace("'", "''") + "'"


goals = [
    ("Pulover urât de Crăciun tot stream-ul", 100), ("Provocarea cu baia de gheață", 250),
    ("Seară de jocuri cu viewerii", 500), ("Concurs de turtă dulce", 750),
    ("Chatul îmi pictează fața", 1000), ("Karaoke cu colinde", 1500),
    ("Gătesc sarmale live", 2000), ("Stream IRL prin zăpadă", 2500),
    ("Chatul îmi alege culoarea părului", 3000), ("Turneu cu comunitatea", 4000),
    ("Baie în lacul înghețat", 5000), ("Obiectiv secret", 7500),
]
prizes = [
    ("+5 min", "+5 minute pe cronometru", True), ("VIP 24h", "VIP pe chat 24 de ore", True),
    ("Shoutout", "Shoutout live pe stream", True), ("Sub cadou", "Un sub cadou de la Iceman", True),
    ("Alegi jocul", "Alegi următorul joc", True), ("O colindă", "Iceman îți cântă o colindă", True),
    ("Îngheți timpul", "Îngheți cronometrul 5 minute", True), ("Mai încearcă", "Mai încearcă", False),
]
# (key, seconds, per, label) -- rates still to be confirmed by the owner.
rates = [
    ("tier1", 60, 1, "Tier 1 / Prime"), ("tier2", 120, 1, "Tier 2"), ("tier3", 300, 1, "Tier 3"),
    ("gift", 60, 1, "Sub cadou (per sub)"), ("bits", 60, 400, "400 de biți"),
    ("donation", 60, 25, "Donație 25 lei"),
]
challenges = json.loads((root / "data/challenges.json").read_text())["challenges"]

lines = [
    "-- FULGATHON phase 2: seed data. Generated by scripts/gen-seed.py; edit the",
    "-- sources (src/data/sample.ts, data/challenges.json) and regenerate.",
    "-- Time rates and goals are the design's values and still need the owner's OK.",
    "",
    "insert into public.rates (key, seconds, per, label) values",
    ",\n".join(f"  ({q(k)}, {s}, {p}, {q(l)})" for k, s, p, l in rates) + ";",
    "",
    "insert into public.goals (position, title, threshold) values",
    ",\n".join(f"  ({i + 1}, {q(t)}, {n})" for i, (t, n) in enumerate(goals)) + ";",
    "",
    "insert into public.prizes (position, short_label, full_label, is_win, weight) values",
    ",\n".join(f"  ({i}, {q(s)}, {q(f)}, {'true' if w else 'false'}, 1)" for i, (s, f, w) in enumerate(prizes)) + ";",
    "",
    "insert into public.challenges (id, category, category_name, title, how, level, votable) values",
    ",\n".join(
        f"  ({c['id']}, {q(c['category'])}, {q(c['category_name'])}, {q(c['title'])}, {q(c['how'])}, {q(c['level'])}, {'true' if c['votable'] else 'false'})"
        for c in challenges
    ) + ";",
    "",
]
out.write_text("\n".join(lines))
print(f"wrote {out.relative_to(root)}: {len(challenges)} challenges, {len(goals)} goals, {len(prizes)} prizes, {len(rates)} rates")
